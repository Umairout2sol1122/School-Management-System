    [Fact]
    public async Task LinkGuardian_ToMultipleStudents_CreatesSiblingConnectionSuccessfully()
    {
        string dbName = $"SiblingLink_{Guid.NewGuid()}";
        var orgId = Guid.NewGuid();
        var adminUserId = Guid.NewGuid();

        var tenantCtx = CreateTenantContext(orgId);
        using var context = CreateInMemoryDbContext(dbName, tenantCtx);

        // Pre-create two students (siblings) and one guardian (father)
        var student1 = new Student
        {
            Id = Guid.NewGuid(),
            OrganizationId = orgId,
            AdmissionNumber = "ADM-SIB-001",
            FirstName = "Hamza",
            LastName = "Kamran",
            CurrentGrade = "Grade 5",
            Gender = Gender.Male,
            DateOfBirth = new DateTime(2015, 1, 1),
            AdmissionDate = DateTime.UtcNow
        };

        var student2 = new Student
        {
            Id = Guid.NewGuid(),
            OrganizationId = orgId,
            AdmissionNumber = "ADM-SIB-002",
            FirstName = "Ayesha",
            LastName = "Kamran",
            CurrentGrade = "Grade 2",
            Gender = Gender.Female,
            DateOfBirth = new DateTime(2018, 1, 1),
            AdmissionDate = DateTime.UtcNow
        };

        var guardian = new Guardian
        {
            Id = Guid.NewGuid(),
            OrganizationId = orgId,
            FirstName = "Kamran",
            LastName = "Akram",
            Phone = "+92 300 9998877",
            RelationshipType = GuardianRelationshipType.Father
        };

        context.Students.AddRange(student1, student2);
        context.Guardians.Add(guardian);
        await context.SaveChangesAsync();

        var studentsController = new StudentsController(context, _auditServiceMock.Object);
        SetupControllerContext(studentsController, adminUserId, orgId, null, UserRoleType.OrganizationAdmin);

        // Link guardian to Student 1
        var link1 = await studentsController.AssignGuardian(student1.Id, new AssignGuardianRequestDto(
            GuardianId: guardian.Id,
            Relationship: "Father",
            IsPrimaryContact: true,
            IsAuthorizedToPickup: true
        ), CancellationToken.None);
        link1.Should().BeOfType<OkObjectResult>();

        // Link same guardian to Student 2
        var link2 = await studentsController.AssignGuardian(student2.Id, new AssignGuardianRequestDto(
            GuardianId: guardian.Id,
            Relationship: "Father",
            IsPrimaryContact: true,
            IsAuthorizedToPickup: true
        ), CancellationToken.None);
        link2.Should().BeOfType<OkObjectResult>();

        // Query Guardian details through GuardiansController
        var guardiansController = new GuardiansController(context, _auditServiceMock.Object);
        SetupControllerContext(guardiansController, adminUserId, orgId, null, UserRoleType.OrganizationAdmin);

        var detailsResult = await guardiansController.GetGuardianById(guardian.Id, CancellationToken.None);
        detailsResult.Should().BeOfType<OkObjectResult>();

        var details = GetData<GuardianDetailsDto>(detailsResult);
        details.Should().NotBeNull();
        details!.LinkedStudents.Should().HaveCount(2);
        details.LinkedStudents.Select(s => s.FullName).Should().Contain(new[] { "Hamza Kamran", "Ayesha Kamran" });
    }

