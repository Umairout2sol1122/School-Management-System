        student.StudentGuardians.Should().HaveCount(1);
        var sg = student.StudentGuardians.First();
        sg.IsPrimaryContact.Should().BeTrue();
        sg.Guardian.Should().NotBeNull();
        sg.Guardian!.FullName.Should().Be("Tariq Khan");
        sg.Guardian.Phone.Should().Be("+92 300 1112233");
