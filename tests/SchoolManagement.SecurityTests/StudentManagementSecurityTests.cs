        string dbName = $"ToggleStaffStatus_{Guid.NewGuid()}";
        var orgId = Guid.NewGuid();
        var adminUserId = Guid.NewGuid();

        var tenantCtx = CreateTenantContext(orgId);
        using var context = CreateInMemoryDbContext(dbName, tenantCtx);

        var user = new User
        {
            Id = Guid.NewGuid(),
            OrganizationId = orgId,
            Username = "teacher@school.edu",
            Email = "teacher@school.edu",
            NormalizedEmail = "TEACHER@SCHOOL.EDU",
            FirstName = "John",
            LastName = "Doe",
            PasswordHash = "hash",
            PasswordSalt = "salt",
            RoleType = UserRoleType.Teacher,
            IsActive = true
        };
        var staff = new StaffProfile
        {
            Id = Guid.NewGuid(),
            OrganizationId = orgId,
            UserId = user.Id,
            EmployeeCode = "EMP-TERM-001",
            Designation = "Math Teacher",
            Department = "Mathematics",
            Status = StaffStatus.Active,
            User = user
        };
        context.Users.Add(user);
        context.StaffProfiles.Add(staff);
        await context.SaveChangesAsync();

        var controller = new StaffController(context, _auditServiceMock.Object, _passwordHasher);
        SetupControllerContext(controller, adminUserId, orgId, null, UserRoleType.OrganizationAdmin);

