            EmergencyContactName: "Tariq Khan",
            EmergencyContactPhone: "+92 300 1112233",
            EmergencyContactRelationship: "Father",
            Address: "House 12, Street 4",
            City: "Islamabad",
            MedicalNotes: "None",
            InitialGuardian: new CreateGuardianRequestDto(
                BranchId: branchId,
                FirstName: "Tariq",
                LastName: "Khan",
                RelationshipType: GuardianRelationshipType.Father,
                NationalId: "12345-1111111-1",
                Email: "tariq@gmail.com",
                Phone: "+92 300 1112233",
                AlternatePhone: null,
                Occupation: "Engineer",
                AnnualIncome: 1200000,
                Address: "House 12, Street 4",
                City: "Islamabad",
                IsEmergencyContact: true
            ),
            GuardianRelationship: "Father",
            IsPrimaryGuardian: true
        );

        var result = await controller.CreateStudent(request, CancellationToken.None);

        result.Should().BeOfType<OkObjectResult>();
